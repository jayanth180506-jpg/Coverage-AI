"""COVERAGE-AI model export to C++ (Stage 13).

Converts the trained scikit-learn DecisionTreeRegressor into a self-contained,
header-only C++ inference module suitable for merging into the ESP32 Arduino
sketch. Also emits a representative test-input CSV plus a C++ test harness
driver so Python and C++ predictions can be compared bit-for-bit.

The exported tree uses double-precision thresholds and values that match
scikit-learn's internal float64 traversal, so C++ and Python agree to within
rounding of the printed values (validated in validate_export.py).

Outputs (models/exported/):
  wifi_rssi_model.h      - header-only model (tree + AP-mean table + predict + coverage)
  test_inputs.csv        - representative feature inputs + Python predictions
  test_model.cpp         - C++ driver that reads test_inputs.csv, predicts, writes cpp
"""
import csv
from pathlib import Path

import numpy as np
import pandas as pd
import joblib

ROOT = Path(__file__).resolve().parents[1]
TRAINED = ROOT / "models" / "trained"
COMP = ROOT / "models" / "comparison"
EXPORTED = ROOT / "models" / "exported"
EXPORTED.mkdir(parents=True, exist_ok=True)

FEATURES = ["x", "y", "floor_id", "building_num", "ap_mean_rssi"]

# Configurable coverage thresholds (initial engineering settings, editable).
COVERAGE = [
    ("EXCELLENT", -50.0, ">="),
    ("GOOD", -60.0, ">= -60 and <= -51"),
    ("FAIR", -70.0, ">= -70 and <= -61"),
    ("POOR", -80.0, ">= -80 and <= -71"),
    ("VERY_POOR", -999.0, "< -80"),
]


def fmt_arr(name, dtype, vals, per_line=8):
    out = [f"static const {dtype} {name}[{len(vals)}] = {{"]
    for i, v in enumerate(vals):
        if i % per_line == 0:
            out.append("  ")
        out.append(f"{v},")
        if (i + 1) % per_line == 0:
            out.append("\n")
    if not out[-1].endswith("\n"):
        out.append("\n")
    out.append("};\n")
    return "".join(out)


def main():
    bundle = joblib.load(TRAINED / "model_bundle.pkl")
    tree = bundle["tree"]
    t = tree.tree_
    n_nodes = t.node_count
    left = t.children_left
    right = t.children_right
    feat = t.feature
    thr = t.threshold
    # leaf value: t.value[node,0,0]
    val = np.asarray([t.value[i, 0, 0] for i in range(n_nodes)], dtype=float)

    bmap = bundle["building_map"]
    ap_mean = bundle["ap_mean_map"]
    gmean = bundle["global_mean_rssi"]

    # sorted AP-mean table for binary search
    ap_items = sorted(ap_mean.items(), key=lambda kv: kv[0])

    lines = []
    lines.append("// wifi_rssi_model.h - AUTO-GENERATED by export_esp32_model.py\n")
    lines.append("// COVERAGE-AI Decision Tree regressor for Wi-Fi RSSI prediction.\n")
    lines.append("// Do not edit by hand; re-generate after retraining.\n")
    lines.append("#pragma once\n#include <cstring>\n")
    lines.append("namespace wifi_model {\n\n")
    lines.append("// Feature order used by predictRSSI:\n")
    lines.append("//   0:x(m) 1:y(m) 2:floor_id 3:building_num 4:ap_mean_rssi(dBm)\n")
    lines.append(f"static const int N_NODES = {n_nodes};\n")
    lines.append(fmt_arr("feature", "int", feat.tolist()))
    lines.append(fmt_arr("threshold", "double",
                         [repr(float(x)) for x in thr.tolist()]))
    lines.append(fmt_arr("left", "int", left.tolist()))
    lines.append(fmt_arr("right", "int", right.tolist()))
    lines.append(fmt_arr("value", "double",
                         [repr(float(x)) for x in val.tolist()]))

    # building map
    lines.append("// building_id (string) -> building_num\n")
    lines.append(f"static const int N_BUILDINGS = {len(bmap)};\n")
    lines.append("struct BuildingEntry { const char* name; int num; };\n")
    lines.append("static const BuildingEntry building_table[N_BUILDINGS] = {\n")
    for k, v in bmap.items():
        lines.append(f'  {{"{k}", {v}}},\n')
    lines.append("};\n")
    lines.append("inline int building_num(const char* name) {\n")
    lines.append("  for (int i=0;i<N_BUILDINGS;++i) if (strcmp(name,building_table[i].name)==0) return building_table[i].num;\n")
    lines.append("  return -1;\n}\n\n")

    # AP-mean table
    lines.append(f"static const int N_AP = {len(ap_items)};\n")
    lines.append("struct ApEntry { const char* bssid; float mean; };\n")
    lines.append("static const ApEntry ap_table[N_AP] = {\n")
    for k, v in ap_items:
        lines.append(f'  {{"{k}", {float(v):.6f}f}},\n')
    lines.append("};\n")
    lines.append(f"static const float GLOBAL_MEAN = {float(gmean):.6f}f;\n")
    lines.append("// binary search (table is sorted by bssid)\n")
    lines.append("inline float ap_mean_rssi(const char* bssid) {\n")
    lines.append("  int lo=0, hi=N_AP-1;\n")
    lines.append("  while (lo<=hi){ int mid=(lo+hi)/2; int c=strcmp(bssid,ap_table[mid].bssid);\n")
    lines.append("    if (c==0) return ap_table[mid].mean; if (c<0) hi=mid-1; else lo=mid+1; }\n")
    lines.append("  return GLOBAL_MEAN;\n}\n\n")

    # predict
    lines.append("// Returns predicted RSSI in dBm for the given location and AP mean.\n")
    lines.append("inline double predictRSSI(double x, double y, int floor_id, int building_num_, double ap_mean_rssi_){\n")
    lines.append("  double feats[5] = {x, y, (double)floor_id, (double)building_num_, ap_mean_rssi_};\n")
    lines.append("  int node = 0;\n")
    lines.append("  while (left[node] != -1) {\n")
    lines.append("    if (feats[feature[node]] <= threshold[node]) node = left[node];\n")
    lines.append("    else node = right[node];\n")
    lines.append("  }\n  return value[node];\n}\n\n")

    # configurable coverage classification
    lines.append("// Configurable coverage thresholds (dBm). Editable for deployment.\n")
    for name, th, _ in COVERAGE:
        lines.append(f"static const double TH_{name} = {th:.1f};\n")
    lines.append("// returns 5=Excellent,4=Good,3=Fair,2=Poor,1=VeryPoor,0=Unknown\n")
    lines.append("inline int coverageClass(double rssi){\n")
    lines.append("  if (rssi >= TH_EXCELLENT) return 5;\n")
    lines.append("  if (rssi >= TH_GOOD) return 4;\n")
    lines.append("  if (rssi >= TH_FAIR) return 3;\n")
    lines.append("  if (rssi >= TH_POOR) return 2;\n")
    lines.append("  if (rssi >= TH_VERY_POOR) return 1;\n")
    lines.append("  return 0;\n}\n")
    lines.append("} // namespace wifi_model\n")
    (EXPORTED / "wifi_rssi_model.h").write_text("".join(lines), encoding="utf-8")
    print("wrote", EXPORTED / "wifi_rssi_model.h", f"({n_nodes} nodes, {len(ap_items)} AP entries)")

    # --- representative test inputs + Python predictions -------------------
    tp = pd.read_csv(COMP / "test_predictions.csv")
    tp["building_num"] = tp["building_id"].map(bmap).astype(int)
    sample = tp.sample(n=min(2000, len(tp)), random_state=7).reset_index(drop=True)
    with open(EXPORTED / "test_inputs.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["x", "y", "floor_id", "building_num", "ap_mean_rssi", "python_pred"])
        for _, r in sample.iterrows():
            w.writerow([f"{r['x']:.10g}", f"{r['y']:.10g}", int(r["floor_id"]),
                        int(r["building_num"]), f"{r['ap_mean_rssi']:.10g}",
                        f"{r['pred_rssi']:.12g}"])
    print("wrote", EXPORTED / "test_inputs.csv", f"({len(sample)} rows)")

    # --- C++ test driver --------------------------------------------------
    driver = """// test_model.cpp - validates wifi_rssi_model.h against Python predictions.
#include "wifi_rssi_model.h"
#include <cstdio>
#include <vector>
#include <string>
int main() {
  FILE* in = fopen("test_inputs.csv", "r");
  if (!in) { fprintf(stderr, "cannot open test_inputs.csv\\n"); return 1; }
  char line[512];
  fgets(line, sizeof(line), in); // header
  FILE* out = fopen("cpp_predictions.csv", "w");
  fprintf(out, "x,y,floor_id,building_num,ap_mean_rssi,python_pred,cpp_pred,abs_diff\\n");
  double x,y,apm,pp; int fl,bn; int n=0; double maxdiff=0.0, sumdiff=0.0;
  while (fgets(line, sizeof(line), in)) {
    if (sscanf(line, "%lf,%lf,%d,%d,%lf,%lf", &x,&y,&fl,&bn,&apm,&pp) == 6) {
      double cp = wifi_model::predictRSSI(x,y,fl,bn,apm);
      double d = cp - pp; if (d<0) d=-d;
      if (d>maxdiff) maxdiff=d; sumdiff+=d; n++;
      fprintf(out, "%.10g,%.10g,%d,%d,%.10g,%.12g,%.12g,%.3e\\n", x,y,fl,bn,apm,pp,cp,d);
    }
  }
  fclose(in); fclose(out);
  printf("rows=%d max_abs_diff=%.9f mean_abs_diff=%.9f\\n", n, maxdiff, sumdiff/(n?n:1));
  return 0;
}
"""
    (EXPORTED / "test_model.cpp").write_text(driver, encoding="utf-8")
    print("wrote", EXPORTED / "test_model.cpp")
    print("next: compile with g++ and compare (validate_export.py)")


if __name__ == "__main__":
    main()
