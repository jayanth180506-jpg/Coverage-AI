"""Estimate and evaluate a constant RSSI offset using held-out device data.

The offset is learned on distinct measurement IDs and scored on held-out IDs.
This does not replace device-specific retraining or correct spatial error.
"""
import argparse
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import GroupShuffleSplit

ROOT = Path(__file__).resolve().parents[1]


def score(actual, predicted):
    e = np.asarray(predicted) - np.asarray(actual)
    return {"mae_dbm": float(np.mean(np.abs(e))),
            "rmse_dbm": float(np.sqrt(np.mean(e ** 2))),
            "bias_dbm": float(np.mean(e))}


def calibrate(csv_path, bundle_path, output, building_num=0):
    d = pd.read_csv(csv_path)
    required = {"bssid", "rssi", "x", "y"}
    if not required.issubset(d.columns):
        raise ValueError("Run ingest_esp32_csv.py first; required columns: bssid,rssi,x,y")
    bundle = joblib.load(bundle_path)
    if "floor_id" not in d: d["floor_id"] = 0
    if "building_id" not in d: d["building_id"] = "SITE"
    d = d.dropna(subset=["bssid", "rssi", "x", "y"]).copy()
    d["building_num"] = d["building_id"].map(bundle["building_map"])
    unknown_building = d["building_num"].isna()
    d["building_num"] = d["building_num"].fillna(int(building_num)).astype(int)
    apmap = bundle["ap_mean_map"]
    gmean = float(bundle["global_mean_rssi"])
    ap_keys = d["bssid"].astype(str)
    d["ap_mean_rssi"] = ap_keys.map(apmap).fillna(gmean)
    d["predicted"] = bundle["tree"].predict(d[bundle["feature_names"]])
    # Group by physical position so repeated AP rows and repeated scans at that
    # point cannot leak from offset fitting into the held-out score.
    groups = (d["building_id"].astype(str) + "|" + d["floor_id"].astype(str) + "|" +
              d["x"].astype(float).round(2).astype(str) + "|" + d["y"].astype(float).round(2).astype(str))
    if pd.Series(groups).nunique() < 2:
        raise ValueError("Need at least two distinct measurement IDs for a held-out calibration evaluation")
    tr, te = next(GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=42)
                  .split(d, groups=groups))
    # RSSI convention: observed - predicted is the additive correction.
    offset = float(np.median(d.iloc[tr]["rssi"].to_numpy() - d.iloc[tr]["predicted"].to_numpy()))
    test = d.iloc[te].copy()
    before = score(test["rssi"], test["predicted"])
    after = score(test["rssi"], test["predicted"] + offset)
    output.parent.mkdir(parents=True, exist_ok=True)
    test.assign(corrected_prediction=test["predicted"] + offset).to_csv(output, index=False)
    calibration_header = ROOT / "esp32" / "wifi_rssi_calibration.h"
    calibration_header.write_text(
        "// Generated by src/calibrate_esp32.py; learned on calibration locations.\n"
        "#pragma once\nnamespace wifi_calibration {\n"
        f"static const double RSSI_OFFSET_DBM = {offset:.17g};\n"
        "}\n", encoding="utf-8")
    sketch_dir = ROOT / "esp32" / "COVERAGE_AI"
    if sketch_dir.exists():
        (sketch_dir / "wifi_rssi_calibration.h").write_text(
            "// Generated by src/calibrate_esp32.py; learned on calibration locations.\n"
            "#pragma once\nnamespace wifi_calibration {\n"
            f"static const double RSSI_OFFSET_DBM = {offset:.17g};\n"
            "}\n", encoding="utf-8")
    active_sketch = ROOT.parent / "coverage-ai.ino"
    if active_sketch.exists():
        (ROOT.parent / "wifi_rssi_calibration.h").write_text(
            "// Generated by src/calibrate_esp32.py after held-out device calibration.\n"
            "#pragma once\nnamespace wifi_calibration {\n"
            f"static const double RSSI_OFFSET_DBM = {offset:.17g};\n"
            "}\n", encoding="utf-8")
    report = output.with_suffix(".md")
    report.write_text(
        "# ESP32 RSSI Calibration Report\n\n"
        f"- Input rows: {len(d)}; calibration rows: {len(tr)}; held-out rows: {len(te)}\n"
        f"- Unknown building IDs assigned to configured model index {building_num}: {int(unknown_building.sum())}\n"
        f"- BSSIDs absent from model AP map (global fallback): {int((~ap_keys.isin(apmap)).sum())} / {len(d)}\n"
        f"- Offset learned on calibration groups: {offset:.3f} dB\n"
        f"- Held-out before: MAE {before['mae_dbm']:.3f}, RMSE {before['rmse_dbm']:.3f}, bias {before['bias_dbm']:.3f} dB\n"
        f"- Held-out after: MAE {after['mae_dbm']:.3f}, RMSE {after['rmse_dbm']:.3f}, bias {after['bias_dbm']:.3f} dB\n\n"
        f"The firmware offset header was written to `{calibration_header.relative_to(ROOT)}`. "
        "This is scalar offset calibration only. If most BSSIDs use the global fallback, "
        "public-data predictions have no AP-specific identity information; collect device "
        "data and retrain before deployment.\n", encoding="utf-8")
    print(f"offset={offset:.3f} dB; held-out MAE {before['mae_dbm']:.3f} -> {after['mae_dbm']:.3f}; report={report}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", type=Path)
    ap.add_argument("--bundle", type=Path, default=ROOT / "models" / "trained" / "benchmark_model_bundle.pkl",
                    help="Public benchmark bundle to compare with ESP32 field measurements")
    ap.add_argument("--output", type=Path, default=ROOT / "models" / "comparison" / "esp32_calibration_predictions.csv")
    ap.add_argument("--building-num", type=int, default=0,
                    help="Explicit model building index for unseen site IDs")
    a = ap.parse_args()
    calibrate(a.csv, a.bundle, a.output, a.building_num)


if __name__ == "__main__":
    main()
