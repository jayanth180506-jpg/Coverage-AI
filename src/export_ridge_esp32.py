"""Export the full-benchmark Ridge model to standalone ESP32 C++ code."""
from pathlib import Path
import shutil
import csv
import joblib
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TRAINED = ROOT / "models" / "trained"
OUT = ROOT / "models" / "exported"
FEATURES = ["x", "y", "floor_id", "building_num", "ap_mean_rssi"]


def main():
    bundle = joblib.load(TRAINED / "model_bundle.pkl")
    ridge = joblib.load(TRAINED / "ridge_model.pkl")
    if len(ridge.coef_) != len(FEATURES):
        raise ValueError("Unexpected Ridge feature count")
    ap_items = sorted(bundle["ap_mean_map"].items())
    lines = ["// Generated by src/export_ridge_esp32.py; do not edit.\n",
             "#pragma once\n#include <cstring>\nnamespace wifi_ridge {\n",
             f"static const int N_AP={len(ap_items)};\n",
             "struct ApEntry { const char* bssid; double mean; };\n",
             "static const ApEntry ap_table[N_AP]={\n"]
    lines += [f'  {{"{k}",{float(v):.17g}}},\n' for k, v in ap_items]
    lines += ["};\n", f"static const double GLOBAL_MEAN={bundle['global_mean_rssi']:.17g};\n",
              "inline double ap_mean_rssi(const char* id){int lo=0,hi=N_AP-1;while(lo<=hi){int m=(lo+hi)/2;int c=strcmp(id,ap_table[m].bssid);if(c==0)return ap_table[m].mean;if(c<0)hi=m-1;else lo=m+1;}return GLOBAL_MEAN;}\n",
              f"static const double INTERCEPT={float(ridge.intercept_):.17g};\n",
              "static const double COEF[5]={" + ",".join(f"{float(v):.17g}" for v in ridge.coef_) + "};\n",
              "inline double predictRSSI(double x,double y,int floor_id,int building_num,double ap_mean){double f[5]={x,y,(double)floor_id,(double)building_num,ap_mean};double p=INTERCEPT;for(int i=0;i<5;++i)p+=COEF[i]*f[i];return p;}\n",
              "inline int coverageClass(double r){if(r>=-50)return 5;if(r>=-60)return 4;if(r>=-70)return 3;if(r>=-80)return 2;return 1;}\n",
              "}\n"]
    (OUT / "wifi_rssi_ridge.h").write_text("".join(lines), encoding="utf-8")
    header_targets = [ROOT / "esp32" / "wifi_rssi_ridge.h"]
    sketch_dir = ROOT / "esp32" / "COVERAGE_AI"
    if sketch_dir.exists():
        header_targets.append(sketch_dir / "wifi_rssi_ridge.h")
    for target in header_targets:
        shutil.copy2(OUT / "wifi_rssi_ridge.h", target)
    active_sketch = ROOT.parent / "coverage-ai.ino"
    if active_sketch.exists():
        shutil.copy2(OUT / "wifi_rssi_ridge.h", ROOT.parent / "wifi_rssi_ridge.h")
    if bundle.get("dataset") != "D5":
        # A scalar correction learned for the public benchmark must not carry
        # over to a separately trained device/site model.
        reset_header = (
            "// Reset by export_ridge_esp32.py for a separately trained dataset.\n"
            "#pragma once\nnamespace wifi_calibration {\n"
            "static const double RSSI_OFFSET_DBM = 0.0;\n}\n")
        (ROOT / "esp32" / "wifi_rssi_calibration.h").write_text(reset_header, encoding="utf-8")
        if sketch_dir.exists():
            (sketch_dir / "wifi_rssi_calibration.h").write_text(reset_header, encoding="utf-8")
        if active_sketch.exists():
            (ROOT.parent / "wifi_rssi_calibration.h").write_text(reset_header, encoding="utf-8")
    tp = pd.read_csv(ROOT / "models" / "comparison" / "test_predictions.csv")
    tp["building_num"] = tp.building_id.map(bundle["building_map"]).astype(int)
    X = tp[FEATURES]
    tp["python_pred"] = ridge.predict(X)
    sample = tp.sample(min(2000, len(tp)), random_state=23).reset_index(drop=True)
    sample[FEATURES + ["python_pred"]].to_csv(OUT / "ridge_test_inputs.csv", index=False)
    driver = r'''#include "wifi_rssi_ridge.h"
#include <cstdio>
int main(){FILE*in=fopen("ridge_test_inputs.csv","r");if(!in)return 1;char line[512];fgets(line,sizeof(line),in);double x,y,a,p;int f,b;double mx=0,sm=0;int n=0;while(fgets(line,sizeof(line),in)){if(sscanf(line,"%lf,%lf,%d,%d,%lf,%lf",&x,&y,&f,&b,&a,&p)==6){double d=wifi_ridge::predictRSSI(x,y,f,b,a)-p;if(d<0)d=-d;if(d>mx)mx=d;sm+=d;n++;}}fclose(in);printf("rows=%d max_abs_diff=%.12g mean_abs_diff=%.12g\\n",n,mx,sm/(n?n:1));return 0;}'''
    (OUT / "ridge_test.cpp").write_text(driver, encoding="utf-8")
    print(f"wrote Ridge header ({len(ap_items)} AP keys); {len(sample)} reference inputs")


if __name__ == "__main__":
    main()
